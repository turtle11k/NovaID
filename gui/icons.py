"""
gui/icons.py
------------
Tiny helper to load the PNG icon set from assets/ (generated by
tools/make_icons.py). Icons are cached so repeated lookups are cheap.

Loading is defensive: if a file is missing the app still runs, just
without that icon, so the GUI never crashes over a missing asset.
"""

from __future__ import annotations

import os
from functools import lru_cache

from PySide6.QtCore import Qt
from PySide6.QtGui import QIcon, QPixmap

ASSETS_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets"
)


def icon_path(name: str) -> str:
    return os.path.join(ASSETS_DIR, f"{name}.png")


@lru_cache(maxsize=None)
def get_icon(name: str) -> QIcon:
    """Return a cached QIcon for assets/<name>.png (empty if absent)."""
    path = icon_path(name)
    return QIcon(path) if os.path.exists(path) else QIcon()


def get_pixmap(name: str, size: int) -> QPixmap:
    """Return a smoothly scaled square QPixmap, or an empty one if absent."""
    path = icon_path(name)
    if not os.path.exists(path):
        return QPixmap()
    pm = QPixmap(path)
    if pm.isNull():
        return pm
    return pm.scaled(
        size, size, Qt.KeepAspectRatio, Qt.SmoothTransformation
    )
